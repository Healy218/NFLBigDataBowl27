"""Eight-week explosion rankings, just for fun: each team's average explosion per game over weeks 1–8.

    uv run python fun/eight_week_explosion/eight_week_explosion.py

Same measures as fun/week1_explosion (starters = at least half of their unit's snaps in the game; game joules =
each starter's top-speed kinetic energy in the game, ½ m v²; explosive axis = their Combine size-adjusted
explosion), for every regular-season game in weeks 1–8 of 2023, 2024 and 2025. Per team and game: the sum over
starters (0 when a team had no tracked starter). Per team: the mean over the games it played in weeks 1–8 (7 or 8:
byes start in week 5), ranked by mean game kJ.

Same caveat: only the 2023–2025 draft classes (WR, TE, DB, OL, DL) are tracked, so this is the explosion of each
team's young starters from those classes, not its whole lineup.

Writes fun/eight_week_explosion/ranking.md (team averages).
"""

from __future__ import annotations

import sys

import polars as pl

from eeg.clustering.audit import _md
from eeg.config import PROJECT_ROOT

sys.path.insert(0, str(PROJECT_ROOT / "fun/week1_explosion"))
from week1_explosion import (  # noqa: E402
    INTERIM,
    PROCESSED,
    RAW,
    SEASONS,
    STARTER_SHARE,
    TEAM_ALIASES,
    game_joules,
    starters,
)

HERE = PROJECT_ROOT / "fun/eight_week_explosion"
FIRST, LAST = 1, 8


def team_games() -> tuple[pl.DataFrame, pl.DataFrame]:
    """Regular-season games in weeks FIRST–LAST (game_id, season) and every team's appearances in them."""
    g = pl.read_csv(RAW / "games.csv").filter((pl.col("season_type") == "REG") & pl.col("week").is_between(FIRST, LAST))
    side = [
        g.select("season", "week", "game_id", pl.col(c).replace(TEAM_ALIASES).alias("team_abbr"))
        for c in ("home_team_abbr", "visitor_team_abbr")
    ]
    return g.select("game_id", "season"), pl.concat(side)


def team_averages(players: pl.DataFrame, appearances: pl.DataFrame) -> pl.DataFrame:
    """Per team: games, mean starters, mean game kJ, mean kJ per starter and mean explosive-axis sum per game."""
    per_game = (
        players.filter("starter")
        .group_by("season", "game_id", "team_abbr")
        .agg(
            pl.len().alias("starters"),
            (pl.col("game_joules").sum() / 1000).alias("game_kJ"),
            pl.col("ax_explosive").sum().alias("axis_sum"),
        )
    )
    g = appearances.join(per_game, on=["season", "game_id", "team_abbr"], how="left").with_columns(
        pl.col("starters", "game_kJ", "axis_sum").fill_null(0)
    )
    t = (
        g.group_by("team_abbr")
        .agg(
            pl.len().alias("games"),
            pl.col("starters").mean().alias("starters_per_game"),
            pl.col("game_kJ").mean().alias("game_kJ_per_game"),
            (pl.col("game_kJ").sum() / pl.col("starters").sum()).fill_nan(None).alias("kJ_per_starter"),
            pl.col("axis_sum").mean().alias("axis_sum_per_game"),
        )
        .sort("game_kJ_per_game", descending=True)
        .with_row_index("rank", offset=1)
        .with_columns(pl.col("axis_sum_per_game").rank("ordinal", descending=True).cast(pl.Int64).alias("axis_rank"))
    )
    return t


def main() -> None:
    cs = pl.read_parquet(INTERIM / "combine_si.parquet")
    groups = cs.select("player_id", pl.col("pos_group").alias("group"))
    mass = cs.select("player_id", "mass_kg")
    axis = pl.read_parquet(PROCESSED / "profiles.parquet").select("player_id", "ax_explosive")
    games, appearances = team_games()
    players = (
        starters(games, groups)
        .join(game_joules(games, mass), on=["game_id", "player_id"], how="left")
        .join(axis, on="player_id", how="left")
    )
    sections = []
    for season in SEASONS:
        a = appearances.filter(pl.col("season") == season)
        t = team_averages(players.filter(pl.col("season") == season), a)
        sections.append(
            f"""## Weeks {FIRST}–{LAST}, {season}

{a["game_id"].n_unique()} games. `game_kJ_per_game`: mean over the team's games of the sum of its starters'
top-speed kinetic energy (kJ); `kJ_per_starter`: all starter joules over all starter-games; `axis_sum_per_game`:
mean sum of starters' Combine explosive axis (profiled starters only). Ranked by `game_kJ_per_game`.

{_md(t, 1)}
"""
        )
    report = f"""# Eight-week explosion rankings (just for fun)

Generated by `uv run python fun/eight_week_explosion/eight_week_explosion.py`. Each team's average explosion per
game over regular-season weeks {FIRST}–{LAST}: starters (≥ {STARTER_SHARE:.0%} of their unit's snaps), their top-speed
kinetic energy in each game, summed per game and averaged over the team's games (7 or 8; byes start in week 5).

**Read with care:** the competition data tracks only the 2023–2025 draft classes in five groups (WR, TE, DB, OL,
DL), so this is the explosion of each team's *young starters from those classes*. Teams that start more of them
score higher; `kJ_per_starter` is the per-player view.

{chr(10).join(sections)}"""
    (HERE / "ranking.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
